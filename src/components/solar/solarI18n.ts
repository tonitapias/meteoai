export const SOLAR_T: Readonly<Record<Language, SolarStrings>> = { ca, es, en, fr };

/** Idioma de l'app → locale d'Intl per a les dates del modal. */
export const SOLAR_LOCALE: Readonly<Record<Language, string>> = { ca: 'ca-ES', es: 'es-ES', en: 'en-US', fr: 'fr-FR' };

const isLanguage = (lang: unknown): lang is Language =>
  lang === 'ca' || lang === 'es' || lang === 'en' || lang === 'fr';

/** Idioma vàlid o 'ca' (qualsevol altre valor cau al català). */
export const solarLang = (lang: unknown): Language => (isLanguage(lang) ? lang : 'ca');

/** Textos de l'idioma, amb el català com a reserva. */
export const solarStrings = (lang: unknown): SolarStrings => SOLAR_T[solarLang(lang)];

/** Locale d'Intl de l'idioma, amb 'ca-ES' com a reserva. */
export const solarLocale = (lang: unknown): string => SOLAR_LOCALE[solarLang(lang)];

/** Omple els placeholders {x}; un placeholder sense valor es deixa tal qual (mai "undefined"). */
export function fill(tpl: string, vars: Readonly<Record<string, string | number>>): string {
  return tpl.replace(/\{(\w+)\}/g, (m, k: string) =>
    Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m);
}

